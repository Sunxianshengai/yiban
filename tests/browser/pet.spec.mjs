import {test,expect} from '@playwright/test';
import {signInAsNewAdmin} from './helpers.mjs';
import {writeFileSync} from 'node:fs';
test('upstream settings, transparent pet, original menu and personal todos',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 await signInAsNewAdmin(page,{prefix:'pet'});
 await page.goto('/pet');
 await expect(page.getByRole('heading',{name:'桌宠配置',exact:true})).toBeVisible();
 await expect(page.getByText('正在加载桌宠配置…')).toHaveCount(0,{timeout:20000});
 await expect(page.locator('.dsh-pet-hit')).toHaveCount(1);
 await page.waitForTimeout(5000);
 writeFileSync('artifacts/pet-ingest/browser-errors.json',JSON.stringify({errors,video:await page.locator('video').evaluateAll(es=>es.map(e=>({src:e.src,width:e.videoWidth,time:e.currentTime,error:e.error?.message,classes:e.className})))} ,null,2));
 await expect.poll(()=>page.locator('.dsh-pet-video.is-front').evaluateAll(es=>es.some(e=>e.videoWidth>0&&e.currentTime>0)),{timeout:25000}).toBe(true);
 await expect(page.getByRole('button',{name:'保存',exact:true}).first()).toBeEnabled();
 await page.getByRole('button',{name:'保存',exact:true}).first().click();
 await expect.poll(async()=>{const data=await (await page.request.get('/api/pet/config')).json();return data.main.pets[0].name;}).toBe('瞌睡小羊');
 await page.screenshot({path:'artifacts/pet-ingest/settings-browser.png',fullPage:true});
 await page.getByRole('button',{name:'关闭桌宠配置'}).click();
 const hit=page.locator('.dsh-pet-hit');await hit.click({button:'right'});
 await page.getByText('查看余额',{exact:true}).click();
 await expect(page.locator('.dsh-pet-bubble').filter({hasText:'积分'})).toBeVisible({timeout:10000});
 await hit.click({button:'right'});
 await expect(page.getByText('睡觉',{exact:true})).toBeVisible();
 await page.screenshot({path:'artifacts/pet-ingest/menu-browser.png'});
 await page.getByText('睡觉',{exact:true}).click();
 await expect.poll(async()=>{const s=await (await page.request.get('/api/pet/state')).json();return s.pets['sleepy-sheep']?.sleep?.data?.sleeping;}).toBe(true);
 await page.request.post('/api/pet/wake?pet=sleepy-sheep');
 const todo=await page.request.post('/api/pet/todos',{data:{text:'桌宠待办测试',dueAt:null}});expect(todo.ok()).toBe(true);
 const result=await (await page.request.get('/api/pet/todos')).json();expect(result.todos.some(t=>t.text==='桌宠待办测试')).toBe(true);
});

test('pet chat commits once, resumes its own thread, and cloned pets have separate profiles',async({page})=>{
 await signInAsNewAdmin(page,{prefix:'pet-chat'});
 await page.goto('/pet');
 await expect(page.locator('.dsh-pet-hit')).toHaveCount(1);
 const config=await (await page.request.get('/api/pet/config')).json();
 const saved=await page.request.put('/api/pet/config',{data:{pets:[config.main.pets[0],{...config.main.pets[0],id:'sheep-two',name:'第二位小羊'}]}});
 expect(saved.ok()).toBe(true);
 await expect(page.locator('.dsh-pet-hit')).toHaveCount(2,{timeout:15000});
 const a=await (await page.request.get('/api/pet/binding?pet=sleepy-sheep')).json();
 const b=await (await page.request.get('/api/pet/binding?pet=sheep-two')).json();
 expect(a.binding.profileId).not.toBe(b.binding.profileId);
 const send=()=>page.request.post('/api/pet/chat?pet=sleepy-sheep',{headers:{'idempotency-key':'pet-browser-replay'},data:{text:'我今天做完了桌宠动画，想和你说说。'},timeout:90000});
 const first=await send();expect(await first.json()).toMatchObject({ok:true,threadId:a.thread.id});
 const replay=await send();expect(await replay.json()).toMatchObject({ok:true,threadId:a.thread.id});
 const history=await (await page.request.get('/api/pet/chat?pet=sleepy-sheep')).json();
 expect(history.messages.filter(m=>m.role==='user')).toHaveLength(1);
 expect(history.messages.filter(m=>m.role==='assistant'&&m.status==='completed')).toHaveLength(1);
 const other=await (await page.request.get('/api/pet/chat?pet=sheep-two')).json();expect(other.messages).toHaveLength(0);
 await expect(page.locator('.dsh-pet-bubble').filter({hasText:'桌宠动画'}).first()).toBeVisible({timeout:10000});
 const crossOrigin=await page.request.put('/api/pet/config',{headers:{origin:'https://untrusted.invalid'},data:{}});expect(crossOrigin.status()).toBe(403);
 await page.goto(`/app?chat=${a.thread.id}&petProfile=${a.binding.profileId}`);
 await expect(page.getByText('我今天做完了桌宠动画，想和你说说。',{exact:true}).first()).toBeVisible({timeout:20000});
});
